import { useEffect, useState } from 'react';
import assets from './assets.json';

type Assets = typeof assets;
export type AssetSlot = keyof Assets;

/** Look up an asset slot. Every asset path in the project lives in assets.json. */
export function getAsset<K extends AssetSlot>(slot: K): Assets[K] {
  return assets[slot];
}

const fontLoads = new Map<string, Promise<void>>();

/** Registers the font once (browser only). Resolves when usable. */
export function loadFont(slot: 'font.ui'): Promise<void> {
  const { path, family } = getAsset(slot);
  let p = fontLoads.get(slot);
  if (!p) {
    p = new FontFace(family, `url(${path})`).load().then((f) => {
      document.fonts.add(f);
    });
    fontLoads.set(slot, p);
  }
  return p;
}

/** React hook: the asset entry plus `ready` once a font slot has loaded (always true for non-fonts). */
export function useAsset<K extends AssetSlot>(slot: K): { asset: Assets[K]; ready: boolean } {
  const asset = getAsset(slot);
  const isFont = asset.kind === 'font';
  const [ready, setReady] = useState(!isFont);
  useEffect(() => {
    if (!isFont) return;
    let alive = true;
    loadFont(slot as 'font.ui')
      .catch(() => undefined)
      .then(() => alive && setReady(true));
    return () => {
      alive = false;
    };
  }, [slot, isFont]);
  return { asset, ready };
}

export interface ObjectAsset {
  kind: 'object';
  path?: string;
  /** true: no art yet, the renderer draws a coloured block */
  placeholder?: boolean;
  /** width of ONE frame (a strip of `frames` frames is `w * frames` wide) */
  w: number;
  h: number;
  /** animation frames laid out left to right in the PNG; frame 0 is the resting pose (default 1) */
  frames?: number;
  /** with `frames` > 1: ms per frame for an ambient forward loop (static under reduced motion). Omit for one-shot-only (`anim` in the object action). */
  frameMs?: number;
  /**
   * Night-only animation: when `true`, the ambient loop only runs at night.
   * During the day (and under reduced-motion at night) the renderer holds `dayFrame` static.
   * At night under reduced motion it shows frame 0 (the base ON frame).
   * The `dayFrame` must be a valid frame index (< `frames`); it is typically the last frame
   * in the strip (an "off" or "idle" pose that is not part of the night loop).
   *
   * Loop range at night: frames 0 … (frames - 2), i.e. the dayFrame (last) is never cycled
   * through at night — it is the day-only static frame.
   */
  nightOnly?: boolean;
  /** index of the static frame shown by day (and under reduced motion by day). See `nightOnly`. */
  dayFrame?: number;
  color: string;
  /** scripted pose: when the object plays `anim`, the player walks to `foot` (object-space native px, where the feet land),
   *  is replaced by this overlay (frames synced to the object's frames; same cell size as the object art, drawn at its top-left)
   *  for the reps, then gets up and walks back. Skipped under prefers-reduced-motion. */
  pose?: { path: string; frames: number; w: number; h: number; foot: { x: number; y: number } };
  /**
   * Tall-grass field effects for a decor patch whose art covers its footprint tile for tile (read by src/world/grassView.ts).
   * `rustle`: frames 1..`frames` of every tile, frame f at x = (f - 1) * w, tile (tx, ty) at (tx * 16, ty * (16 + head));
   * `head` px of headroom above each tile for leaves. `tips`: frames 0..`frames` of the blades drawn over an actor's legs,
   * same layout as the art (frame f at x = f * w). Generated by grass_fx() in scripts/slice-sprites.py.
   */
  field?: { rustle: { path: string; frames: number; frameMs: number; head: number }; tips: { path: string } };
}
export function getObjectAsset(slot: string): ObjectAsset {
  return assets[slot as AssetSlot] as unknown as ObjectAsset;
}
export function getSfxPath(slot: string): string | undefined {
  return (assets[slot as AssetSlot] as { path?: string } | undefined)?.path;
}
export function sfxSlots(): string[] {
  return Object.keys(assets).filter((k) => k.startsWith('sfx.'));
}
/** Chip icon (16x16 native) for an object id (or `card`), from the `icon.<id>` slots. */
export function getIconPath(id: string): string | undefined {
  return (assets[`icon.${id}` as AssetSlot] as { path?: string } | undefined)?.path;
}

export interface EmoteAsset {
  kind: 'emote';
  path: string;
  /** native width of ONE frame; the strip is `w * frames` wide */
  w: number;
  h: number;
  frames: number;
}
export function getEmoteAsset(slot: string): EmoteAsset | null {
  return (assets[slot as AssetSlot] as unknown as EmoteAsset | undefined) ?? null;
}
